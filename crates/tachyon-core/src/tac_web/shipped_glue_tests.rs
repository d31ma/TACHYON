#![allow(clippy::expect_used)]

use super::WebEngine;
use crate::template::shipped_script_tests::Equivalence;

struct ShippedGlue;

impl ShippedGlue {
    const NOTICE: &str = "// Generated by Tachyon (ADR 0035, ADR 0037): the page's side of the companion\n// protocol, around every web service of one language.\n";
    const GO_GLUE: &str = "// Copyright 2018 The Go Authors. All rights reserved.\n// license that can be found in the LICENSE file.\n\"use strict\";\n\n(() => {\n  // Map the page to the Go program.\n  globalThis.Go = class {\n    /** Starts the program. */\n    run() {}\n  }\n})();\n";
    const SHIPPED_GO_GLUE: &str = "// Copyright 2018 The Go Authors. All rights reserved.\n// license that can be found in the LICENSE file.\n\"use strict\";\n(() => {\nglobalThis.Go = class {\nrun() {}\n}\n})();\n";

    const PYTHON_ENGINE: &str = include_str!("../tac_python/python_host.js");

    fn engines() -> Vec<String> {
        vec![
            WebEngine::linear_memory(WebEngine::RUST_INSTANCE),
            WebEngine::linear_memory(WebEngine::SWIFT_INSTANCE),
            String::from(WebEngine::CSHARP_ENGINE),
            String::from(WebEngine::GO_ENGINE),
            String::from(WebEngine::KOTLIN_ENGINE),
            String::from(WebEngine::JAVA_ENGINE),
            String::from(WebEngine::RUBY_ENGINE),
            WebEngine::linear_memory(crate::native::CppWebServices::INSTANCE),
            String::from(Self::PYTHON_ENGINE),
        ]
    }

    fn authored(engine: &str) -> String {
        format!(
            "{}{engine}{}",
            WebEngine::SHARED_HEAD,
            WebEngine::SHARED_TAIL
        )
    }
}

#[test]
fn a_shared_module_keeps_its_notice_and_ships_without_comments_or_indentation() {
    for engine in ShippedGlue::engines() {
        let shipped = WebEngine::shared_source(&engine);
        let code = shipped
            .strip_prefix(ShippedGlue::NOTICE)
            .expect("the shared module names its source");

        assert!(!code.starts_with(' '), "{code}");
        assert!(!code.contains("\n "), "{code}");
        assert!(!code.contains("\n//"), "{code}");
        assert!(!code.contains("/**"), "{code}");
        assert!(shipped.len() < ShippedGlue::authored(&engine).len());
    }
}

#[test]
fn every_shared_module_is_the_same_program_after_compaction() {
    if !Equivalence::bun_available() {
        eprintln!("skipping: bun is unavailable");
        return;
    }
    for engine in ShippedGlue::engines() {
        let authored = ShippedGlue::authored(&engine);
        let result = Equivalence::same_program(&authored, &WebEngine::shared_source(&engine));

        assert_eq!(result, "same", "{engine}");
    }
}

#[test]
fn the_go_glue_keeps_its_license_and_ships_without_comments_or_indentation() {
    let shipped = WebEngine::shipped_glue(ShippedGlue::GO_GLUE.as_bytes().to_vec());

    assert_eq!(
        String::from_utf8(shipped).expect("text"),
        ShippedGlue::SHIPPED_GO_GLUE
    );
}

#[test]
fn go_glue_that_is_not_text_ships_unchanged() {
    let glue = vec![0xff, b' ', b' ', b'\n'];

    assert_eq!(WebEngine::shipped_glue(glue.clone()), glue);
}
